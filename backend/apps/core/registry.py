def coerce(defn: SettingDef, value: Any) -> Any:
    t = defn.type
    if value is None and t in ("channel_list",) and defn.scope == USER:
        return None
    if t == "bool":
        if not isinstance(value, bool):
            raise SettingError("Must be true or false.")
    elif t == "int":
        try:
            value = int(value)
        except (TypeError, ValueError):
            raise SettingError("Must be a whole number.")
        if defn.min is not None and value < defn.min:
            raise SettingError(f"Must be at least {defn.min}.")
        if defn.max is not None and value > defn.max:
            raise SettingError(f"Must be at most {defn.max}.")
    elif t in ("str", "secret", "path", "email", "url"):
        if not isinstance(value, str):
            raise SettingError("Must be text.")
        value = value.strip() if t != "secret" else value
        if defn.max is not None and len(value) > defn.max:
            raise SettingError(f"Must be at most {defn.max} characters.")
        if t == "email" and value and not re.fullmatch(r"[^@\s]+@[^@\s]+\.[^@\s]+", value):
            raise SettingError("Enter a valid email address.")
        if t == "path" and value and not value.startswith("/"):
            raise SettingError("Enter an absolute path such as /mnt/nas-backup.")
    elif t == "choice":
        if value not in defn.choices:
            raise SettingError(f"Choose one of: {', '.join(defn.choices)}.")
    elif t == "choice_list":
        if not isinstance(value, list) or any(v not in defn.choices for v in value):
            raise SettingError(f"Choose from: {', '.join(defn.choices)}.")
        value = [c for c in defn.choices if c in value]
    elif t == "int_list":
        if isinstance(value, str):
            value = [v for v in re.split(r"[,\s]+", value) if v]
        try:
            value = [int(v) for v in value]
        except (TypeError, ValueError):
            raise SettingError("Enter whole numbers separated by commas.")
    elif t == "channel_list":
        if not isinstance(value, list) or any(v not in CHANNELS for v in value):
            raise SettingError(f"Channels must be from: {', '.join(CHANNELS)}.")
        value = [c for c in CHANNELS if c in value]
    elif t == "event_list":
        if not isinstance(value, list) or any(v not in NOTIFY_EVENTS for v in value):
            raise SettingError("Unknown notification event.")
        if defn.key == "notifications.critical_events":  # some security events can never be made optional
            value = list(value) + [k for k, e in NOTIFY_EVENTS.items() if e.always_critical]
        value = [k for k in NOTIFY_EVENTS if k in value]
    elif t == "event_matrix":
        from apps.notify.catalog import coerce_prefs

        value = coerce_prefs(value)
    elif t == "widget_list":
        if not isinstance(value, (list, str)) or (isinstance(value, list) and any(v not in WIDGETS for v in value)):
            raise SettingError(f"Widgets must be from: {', '.join(WIDGETS)}.")
        value = normalize_widgets(value)
    elif t == "country_list":
        from .overview import country_names

        names = country_names()
        if isinstance(value, str):
            value = [v for v in re.split(r"[,\s]+", value) if v]
        if not isinstance(value, list) or any(not isinstance(v, str) or v.upper() not in names for v in value):
            raise SettingError("Choose countries from the list.")
        value = list(dict.fromkeys(v.upper() for v in value))
        if len(value) > 12:
            raise SettingError("Choose at most 12 countries.")
    elif t == "overview_layout":
        from .overview import normalize_layout

        value = normalize_layout(value)
    elif t == "json" and defn.key in ("me.weather_city", "weather.default_city"):
        from .overview import normalize_city

        value = normalize_city(value)
    elif t == "time":
        if not isinstance(value, str) or (value and not re.fullmatch(r"([01]\d|2[0-3]):[0-5]\d", value)):
            raise SettingError("Use 24-hour HH:MM, for example 08:00.")
    elif t == "timezone":
        try:
            zoneinfo.ZoneInfo(value)
        except Exception:
            raise SettingError("Unknown timezone. Use a name like Asia/Riyadh.")
    if defn.validator:
        defn.validator(value)
    if t == "int_list":
        value = sorted(value, reverse=True)
    return value
