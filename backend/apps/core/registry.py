def _validate_group_mapping(value):
    if value in (None, ""):
        return
    if not isinstance(value, dict) or len(value) > 50:
        raise SettingError("Map authentik group names to a role.")
    for group, role in value.items():
        if not isinstance(group, str) or not group.strip() or len(group) > 120:
            raise SettingError("Group names must be non-empty text.")
        if role not in ("member", "administrator"):
            raise SettingError("Groups can only map to the Member or Administrator role (never Main administrator).")


def normalize_widgets(value) -> list[str]:
    """Ordered, de-duplicated widget ids. Accepts the old comma-separated text, in which only the counters were
    chosen and every other section was always shown (kept so upgrades look the same)."""
    if isinstance(value, str):
        chosen = [v.strip() for v in value.split(",") if v.strip() in WIDGETS]
        chosen += ["review"] + [w for w in WIDGETS if w not in STAT_WIDGETS]
        value = chosen
    out: list[str] = []
    for v in value or []:
        if v in WIDGETS and v not in out:
            out.append(v)
    return out


def _validate_thresholds(value):
    if len(value) == 0:
        raise SettingError("Choose at least one reminder day.")
    if len(set(value)) != len(value):
        raise SettingError("Reminder days must be unique.")
    for v in value:
        if v < 0 or v > 730:
            raise SettingError("Reminder days must be between 0 and 730.")


_HOST_RX = re.compile(r"^(?=.{1,253}$)([A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?)(\.[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?)*$|^\[?[0-9A-Fa-f:.]+\]?$")


def _validate_host(value: str):
    if value and not _HOST_RX.match(value):
        raise SettingError("Enter a hostname or IP address, e.g. 192.168.1.20 or nas.local.")


def _validate_share(value: str):
    if value and (not re.fullmatch(r"[A-Za-z0-9/_.\- $]{1,200}", value) or ".." in value.split("/")):
        raise SettingError("Use letters, numbers, spaces and / _ . - $ only.")


def _validate_subfolder(value: str):
    if value and (not re.fullmatch(r"[A-Za-z0-9_.\-]{1,100}", value) or value in (".", "..")):
        raise SettingError("Use a single folder name (letters, numbers, _ . -).")


def _validate_plain(value: str):
    if value and not re.fullmatch(r"[^\s,=\\'\"\x00-\x1f]{1,100}", value):
        raise SettingError("Spaces, commas, quotes, backslashes and '=' are not allowed.")


def _validate_version(value: str):
    if value and not re.fullmatch(r"[0-9](\.[0-9])?", value):
        raise SettingError("Enter a version such as 4.1 or 3.0.")


def _validate_template(value: str):
    if ".." in value or value.startswith("/") or "\\" in value:
        raise SettingError("Templates cannot contain '..', '\\' or start with '/'.")
    allowed = {"owner", "type", "title", "year", "month", "version_id", "document_id", "original_name"}
    for name in re.findall(r"{([^}]*)}", value):
        if name not in allowed:
            raise SettingError(f"Unknown placeholder {{{name}}}. Allowed: {', '.join(sorted(allowed))}.")
    if "{version_id}" not in value:
        raise SettingError("Template must include {version_id} so files never collide.")


